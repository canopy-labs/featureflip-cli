package typegen

import (
	"os"
	"strings"
	"testing"
)

func TestGenerateGolden(t *testing.T) {
	want, err := os.ReadFile("testdata/golden.ts")
	if err != nil {
		t.Fatal(err)
	}
	// Input order and duplicate values must not matter.
	got, warnings := Generate("web", []FlagSpec{
		{Key: "theme", Type: "String", Values: []string{"light", "dark", "light"}},
		{Key: "new-checkout", Type: "Boolean"},
		{Key: "max-items", Type: "Number"},
		{Key: "banner-config", Type: "Json"},
	})
	if len(warnings) != 0 {
		t.Errorf("warnings = %v", warnings)
	}
	if string(got) != string(want) {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestGenerateEscapesQuotesAndNewlines(t *testing.T) {
	got, _ := Generate("web", []FlagSpec{
		{Key: "it's", Type: "String", Values: []string{`a'b`, "line1\nline2", `back\slash`, "tab\there", "sep\u2028x"}},
	})
	src := string(got)
	for _, want := range []string{
		`'it\'s': `,
		`'a\'b'`,
		`'line1\nline2'`,
		`'back\\slash'`,
		`'tab\there'`,
		`'sep\u2028x'`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %s in:\n%s", want, src)
		}
	}
	if strings.Count(src, "\n") != 8 {
		t.Errorf("a raw newline leaked into a literal:\n%s", src)
	}
}

func TestGenerateUnknownTypeWarns(t *testing.T) {
	got, warnings := Generate("web", []FlagSpec{{Key: "when", Type: "Date"}})
	if !strings.Contains(string(got), "'when': unknown;") {
		t.Errorf("got:\n%s", got)
	}
	if len(warnings) != 1 || warnings[0] != "flag when has type Date, which this CLI doesn't know; typed as unknown" {
		t.Errorf("warnings = %v", warnings)
	}
}

func TestGenerateStringWithoutVariationsIsString(t *testing.T) {
	got, _ := Generate("web", []FlagSpec{{Key: "s", Type: "String"}})
	if !strings.Contains(string(got), "'s': string;") {
		t.Errorf("got:\n%s", got)
	}
}

func TestGenerateEmpty(t *testing.T) {
	got, _ := Generate("web", nil)
	want := "// Generated by `featureflip generate types` for project web. Do not edit.\n" +
		"export const flagKeys = [] as const;\n" +
		"export type FlagKey = (typeof flagKeys)[number];\n" +
		"export interface FlagValues {}\n"
	if string(got) != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
}
