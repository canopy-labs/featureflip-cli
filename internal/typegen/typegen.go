// Package typegen renders a project's flags as TypeScript types.
package typegen

import (
	"fmt"
	"sort"
	"strings"
)

// FlagSpec is what the generator needs to know about one flag. Values is
// used only for String flags: the variation values it can serve.
type FlagSpec struct {
	Key    string
	Type   string
	Values []string
}

// Generate renders flags as a TypeScript module. The output depends only on
// its input (sorted, no timestamp), so it diffs cleanly and can be checked
// for drift in CI.
func Generate(project string, flags []FlagSpec) ([]byte, []string) {
	sorted := append([]FlagSpec(nil), flags...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Key < sorted[j].Key })

	var b strings.Builder
	var warnings []string
	fmt.Fprintf(&b, "// Generated by `featureflip generate types` for project %s. Do not edit.\n", project)
	if len(sorted) == 0 {
		b.WriteString("export const flagKeys = [] as const;\n")
		b.WriteString("export type FlagKey = (typeof flagKeys)[number];\n")
		b.WriteString("export interface FlagValues {}\n")
		return []byte(b.String()), nil
	}

	b.WriteString("export const flagKeys = [\n")
	for _, f := range sorted {
		fmt.Fprintf(&b, "  %s,\n", literal(f.Key))
	}
	b.WriteString("] as const;\n")
	b.WriteString("export type FlagKey = (typeof flagKeys)[number];\n")
	b.WriteString("export interface FlagValues {\n")
	for _, f := range sorted {
		tsType, warning := typeOf(f)
		if warning != "" {
			warnings = append(warnings, warning)
		}
		fmt.Fprintf(&b, "  %s: %s;\n", literal(f.Key), tsType)
	}
	b.WriteString("}\n")
	return []byte(b.String()), warnings
}

func typeOf(f FlagSpec) (string, string) {
	switch f.Type {
	case "Boolean":
		return "boolean", ""
	case "Number":
		return "number", ""
	case "Json":
		return "unknown", ""
	case "String":
		seen := map[string]bool{}
		var values []string
		for _, v := range f.Values {
			if !seen[v] {
				seen[v] = true
				values = append(values, v)
			}
		}
		if len(values) == 0 {
			return "string", ""
		}
		sort.Strings(values)
		lits := make([]string, len(values))
		for i, v := range values {
			lits[i] = literal(v)
		}
		return strings.Join(lits, " | "), ""
	}
	return "unknown", fmt.Sprintf("flag %s has type %s, which this CLI doesn't know; typed as unknown", f.Key, f.Type)
}

// literal renders s as a single-quoted TypeScript string literal.
func literal(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\'':
			b.WriteString(`\'`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case ' ', ' ':
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\x%02x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('\'')
	return b.String()
}
