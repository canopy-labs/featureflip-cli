func TestGenerateUnknownTypeWarnsOnStderr(t *testing.T) {
	api := newFakeAPI(t)
	api.on("GET", flagsPath, 200, `{"items":[`+flagItem("when", "Date")+`],"next_cursor":null}`)
	out, errOut, code := run(t, runOpts{API: api, Env: scoped}, "generate", "types")
	if code != 0 || !strings.Contains(out, "'when': unknown;") || !strings.Contains(errOut, "Warning: flag when has type Date") {
		t.Fatalf("exit %d stdout %q stderr %q", code, out, errOut)
	}
}

func TestGenerateJSONStdout(t *testing.T) {
	out, _, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--json")
	if code != 0 {
		t.Fatalf("exit %d", code)
	}
	var doc map[string]any
	if err := json.Unmarshal([]byte(out), &doc); err != nil {
		t.Fatalf("stdout not JSON: %q", out)
	}
	if doc["project"] != "web" || doc["flags"] != float64(3) || doc["source"] != typesOutput || doc["out"] != nil {
		t.Errorf("doc = %v", doc)
	}
}

func TestGenerateJSONWithOutAndCheck(t *testing.T) {
	path := filepath.Join(t.TempDir(), "flags.ts")
	out, _, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--json")
	var doc map[string]any
	if code != 0 || json.Unmarshal([]byte(out), &doc) != nil || doc["out"] != path || doc["written"] != true || doc["source"] != nil {
		t.Fatalf("exit %d stdout %q", code, out)
	}
	out, _, code = run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--check", "--json")
	doc = nil
	if code != 0 || json.Unmarshal([]byte(out), &doc) != nil || doc["upToDate"] != true {
		t.Fatalf("exit %d stdout %q", code, out)
	}
	os.WriteFile(path, []byte("stale\n"), 0o644)
	out, _, code = run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--check", "--json")
	doc = nil
	if code != 7 || json.Unmarshal([]byte(out), &doc) != nil || doc["error"] != "drift" {
		t.Fatalf("exit %d stdout %q", code, out)
	}
}
