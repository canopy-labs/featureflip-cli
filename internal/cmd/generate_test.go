// typesAPI serves a Boolean flag and two String flags with variations.
func typesAPI(t *testing.T) *fakeAPI {
	t.Helper()
	api := newFakeAPI(t)
	api.on("GET", flagsPath, 200, `{"items":[`+flagItem("new-checkout", "Boolean")+`,`+flagItem("theme", "String")+`,`+flagItem("tier", "String")+`],"next_cursor":null}`)
	api.on("GET", flagsPath+"/theme", 200, `{"id":"f2","key":"theme","name":"Theme","type":"String","isArchived":false,"clientSideVisible":true,"tags":[],
		"variations":[{"id":"v1","key":"dark","name":"Dark","value":"dark"},{"id":"v2","key":"light","name":"Light","value":"light"}]}`)
	api.on("GET", flagsPath+"/tier", 200, `{"id":"f3","key":"tier","name":"Tier","type":"String","isArchived":false,"clientSideVisible":false,"tags":[],
		"variations":[{"id":"v3","key":"free","name":"Free","value":"free"},{"id":"v4","key":"pro","name":"Pro","value":"pro"}]}`)
	return api
}

const typesOutput = "// Generated by `featureflip generate types` for project web. Do not edit.\n" +
	"export const flagKeys = [\n  'new-checkout',\n  'theme',\n  'tier',\n] as const;\n" +
	"export type FlagKey = (typeof flagKeys)[number];\n" +
	"export interface FlagValues {\n  'new-checkout': boolean;\n  'theme': 'dark' | 'light';\n  'tier': 'free' | 'pro';\n}\n"

func TestGenerateCmdFetchesOnlyStringFlags(t *testing.T) {
	api := typesAPI(t)
	out, _, code := run(t, runOpts{API: api, Env: scoped}, "generate", "types")
	if code != 0 {
		t.Fatalf("exit %d", code)
	}
	if out != typesOutput {
		t.Errorf("stdout:\n%s", out)
	}
	if n := len(api.calls("GET", flagsPath+"/new-checkout")); n != 0 {
		t.Errorf("fetched the boolean flag's detail %d times", n)
	}
	if n := len(api.calls("GET", flagsPath+"/theme")) + len(api.calls("GET", flagsPath+"/tier")); n != 2 {
		t.Errorf("%d string detail fetches, want 2", n)
	}
	if q := api.calls("GET", flagsPath)[0].Query; q.Get("archived") != "false" {
		t.Errorf("query = %v, want archived=false (the server includes archived flags otherwise)", q)
	}
}

func TestGenerateCmdWritesOut(t *testing.T) {
	path := filepath.Join(t.TempDir(), "flags.ts")
	out, errOut, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path)
	if code != 0 || out != "" {
		t.Fatalf("exit %d stdout %q", code, out)
	}
	got, _ := os.ReadFile(path)
	if string(got) != typesOutput {
		t.Errorf("file:\n%s", got)
	}
	if !strings.Contains(errOut, "Wrote 3 flags to "+path) {
		t.Errorf("stderr = %q", errOut)
	}
}

func TestGenerateCheckDrift(t *testing.T) {
	path := filepath.Join(t.TempDir(), "flags.ts")
	os.WriteFile(path, []byte("stale\n"), 0o644)
	_, errOut, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--check")
	if code != 7 {
		t.Fatalf("exit %d, want 7", code)
	}
	if got, _ := os.ReadFile(path); string(got) != "stale\n" {
		t.Error("--check wrote the file")
	}
	if !strings.Contains(errOut, path+" is out of date; run featureflip generate types --out "+path) {
		t.Errorf("stderr = %q", errOut)
	}
}

