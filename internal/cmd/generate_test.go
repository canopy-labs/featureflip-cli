// A Windows checkout with core.autocrlf turns the committed LF file into CRLF;
// the content is the same, so --check must pass.
func TestGenerateCheckIgnoresCRLF(t *testing.T) {
	path := filepath.Join(t.TempDir(), "flags.ts")
	os.WriteFile(path, []byte(strings.ReplaceAll(typesOutput, "\n", "\r\n")), 0o644)
	_, errOut, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--check")
	if code != 0 {
		t.Fatalf("exit %d, want 0; stderr %q", code, errOut)
	}
}

// Line endings are the only thing --check forgives.
func TestGenerateCheckCRLFStillCatchesDrift(t *testing.T) {
	path := filepath.Join(t.TempDir(), "flags.ts")
	stale := strings.Replace(typesOutput, "'pro'", "'enterprise'", 1)
	os.WriteFile(path, []byte(strings.ReplaceAll(stale, "\n", "\r\n")), 0o644)
	_, _, code := run(t, runOpts{API: typesAPI(t), Env: scoped}, "generate", "types", "--out", path, "--check")
	if code != 7 {
		t.Fatalf("exit %d, want 7", code)
	}
}

